def _base_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent
    p = Path(__file__).resolve().parent
    if p.name == "actions":
        return p.parent
    return p

def _get_os() -> str:
    _sys = platform.system()
    if _sys == "Darwin":
        return "mac"
    if _sys == "Linux":
        return "linux"
    return "windows"

def _scripts_dir() -> Path:
    d = Path.home() / ".jarvis" / "reminders"
    d.mkdir(parents=True, exist_ok=True)
    return d

def _sanitise(text: str, max_len: int = 200) -> str:
    return (
        text.replace("\\", "")
            .replace('"', "")
            .replace("'", "")
            .replace("\n", " ")
            .replace("\r", "")
            .strip()
    )[:max_len]

def _find_alarm_file() -> Path:
    """Finds alarm.mp3 with automatic fallback across common directory structures."""
    base = _base_dir()
    candidates = [
        base / "alarm" / "alarm.mp3",
        base / "sounds" / "alarm.mp3",
        Path.cwd() / "alarm" / "alarm.mp3",
        Path.cwd() / "sounds" / "alarm.mp3",
        Path(__file__).resolve().parent / "alarm" / "alarm.mp3",
        Path(__file__).resolve().parent.parent / "alarm" / "alarm.mp3",
    ]
    for c in candidates:
        if c.exists() and c.is_file():
            return c.resolve()
    return (base / "alarm" / "alarm.mp3").resolve()

def _parse_target_time(raw_date: str, raw_time: str, raw_msg: str) -> datetime:
    """
    Intelligently parses:
    - Relative seconds, minutes, hours ('10s', '10 seconds', '30s', '5m', '2 hours')
    - Exact clock times ('12:00', '12:10', '12:10:10', '10:31 pm', '22:31')
    - Next-occurrence logic (e.g. 12:00 will automatically roll over to tomorrow if past)
    """
    now = datetime.now()
    combined = f"{raw_time} {raw_date} {raw_msg}".lower().replace(",", ":")

    # 1. Check for relative durations
    sec_match = re.search(r"(\d+)\s*(?:s\b|sec\b|secs\b|second\b|seconds\b)", combined)
    min_match = re.search(r"(\d+)\s*(?:m\b|min\b|mins\b|minute\b|minutes\b)", combined)
    hr_match  = re.search(r"(\d+)\s*(?:h\b|hr\b|hrs\b|hour\b|hours\b)", combined)

    if sec_match or min_match or hr_match:
        added_s = int(sec_match.group(1)) if sec_match else 0
        added_m = int(min_match.group(1)) if min_match else 0
        added_h = int(hr_match.group(1)) if hr_match else 0
        total_seconds = added_h * 3600 + added_m * 60 + added_s
        if total_seconds > 0:
            return now + timedelta(seconds=total_seconds)

    # 2. Check for plain number passed as duration (e.g. time="10" or "30")
    if raw_time.strip().isdigit():
        val = int(raw_time.strip())
        if val <= 60:
            return now + timedelta(seconds=val)

    # 3. Check for absolute time: HH:MM:SS or HH:MM with optional AM/PM
    clean_time = raw_time.replace(",", ":").strip()
    time_match = re.search(r"(\d{1,2}):(\d{2})(?::(\d{2}))?\s*(am|pm)?", clean_time)
    
    if time_match:
        hh = int(time_match.group(1))
        mm = int(time_match.group(2))
        ss = int(time_match.group(3)) if time_match.group(3) else 0
        ampm = time_match.group(4).lower() if time_match.group(4) else None

        if ampm == "pm" and hh < 12:
            hh += 12
        elif ampm == "am" and hh == 12:
            hh = 0

        target_date = now.date()
        if "tomorrow" in raw_date or "kal" in raw_date:
            target_date += timedelta(days=1)
        elif re.search(r"\d{4}-\d{2}-\d{2}", raw_date):
            try:
                target_date = datetime.strptime(raw_date.strip(), "%Y-%m-%d").date()
            except Exception:
                pass

        target_dt = datetime.combine(target_date, datetime.min.time()).replace(
            hour=hh, minute=mm, second=ss, microsecond=0
        )

        # Smart Next-Occurrence: If time passed earlier today, roll to tomorrow
        if target_dt <= now and target_date == now.date():
            diff = (now - target_dt).total_seconds()
            if diff > 10:
                if ampm is None and hh < 12:
                    pm_candidate = target_dt.replace(hour=hh + 12)
                    if pm_candidate > now:
                        return pm_candidate
                return target_dt + timedelta(days=1)

        return target_dt

    return now + timedelta(seconds=60)

